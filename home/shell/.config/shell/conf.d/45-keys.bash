# The same keys as in Zellij, for when there is no Zellij around: Zellij takes them
# first, so inside it these never run.
bind '"\ee": "y\n"'                  # Alt-e: yazi
bind '"\eg": "lazygit\n"'            # Alt-g: lazygit
bind '"\e/": "dots palette\n"'       # Alt-/: search everything
bind '"\e?": "dots palette help\n"'  # Alt-?: help; by default it lists every command
bind '"\eu": "dots palette tui\n"'   # Alt-u: pick a TUI
